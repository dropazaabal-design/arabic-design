// Editable SVG art → React/TSX parts, with SVGR (motion-core/art/characters/*.svg → src/characters/<name>/Art.tsx).
//
// Each top-level <g data-part="…" data-pivot="x,y" [data-anchor="x,y"]> becomes one component that keeps its
// data-part, plus PIVOTS / ANCHORS tables the rig reads. SVGO is off so groups and names survive as drawn.
// usage: node tools/svgr-build.mjs sultan [--check]   (--check: exit 1 if the committed Art.tsx is stale)
import { transform } from '@svgr/core';
import jsx from '@svgr/plugin-jsx';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cap = (s) => s[0].toUpperCase() + s.slice(1);

/** Top-level <g data-part> groups of the source, with their pivots and inner markup. */
export function parts(svg) {
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  const out = [];
  const re = /<g\b[^>]*>|<\/g>/g;
  let depth = 0, start = -1, head = '', m;
  while ((m = re.exec(body))) {
    if (m[0] !== '</g>') {
      if (depth === 0) { start = re.lastIndex; head = m[0]; }
      depth++;
    } else if (--depth === 0) {
      const attr = (k) => head.match(new RegExp(`${k}="([^"]+)"`))?.[1];
      const name = attr('data-part');
      if (!name) throw new Error(`top-level group without data-part: ${head}`);
      const xy = (v) => v && v.split(',').map(Number);
      out.push({ name, pivot: xy(attr('data-pivot')) ?? [0, 0], anchor: xy(attr('data-anchor')), inner: body.slice(start, m.index) });
    }
  }
  if (depth !== 0) throw new Error('unbalanced <g> in source');
  return out;
}

// The template turns SVGR's <svg> root into <g data-part="…">: a part, not a document.
const template = (v, { tpl }) => {
  const el = v.jsx;
  el.openingElement.name.name = 'g';
  if (el.closingElement) el.closingElement.name.name = 'g';
  el.openingElement.attributes = [{ type: 'JSXAttribute', name: { type: 'JSXIdentifier', name: 'data-part' }, value: { type: 'StringLiteral', value: v.componentName.replace(/^Part(.)/, (_, c) => c.toLowerCase()) } }];
  return tpl`export const ${v.componentName} = () => ${el};`;
};

export async function build(name) {
  const svg = fs.readFileSync(path.join(root, `art/characters/${name}.svg`), 'utf8');
  const ps = parts(svg);
  const comps = [];
  for (const p of ps) {
    const code = await transform(`<svg xmlns="http://www.w3.org/2000/svg">${p.inner}</svg>`,
      { plugins: [jsx], typescript: true, jsxRuntime: 'automatic', expandProps: false, dimensions: false, svgo: false, template },
      { componentName: `Part${cap(p.name)}` });
    comps.push(code.trim());
  }
  const table = (k) => `{\n${ps.filter((p) => p[k]).map((p) => `  ${p.name}: [${p[k].join(', ')}],`).join('\n')}\n}`;
  return [
    `// Generated by tools/svgr-build.mjs from art/characters/${name}.svg with SVGR. Do not edit: edit the SVG and rebuild.`,
    ...comps,
    `export const PARTS = {\n${ps.map((p) => `  ${p.name}: Part${cap(p.name)},`).join('\n')}\n} as const;`,
    `export type PartName = keyof typeof PARTS;`,
    `/** The joint each part turns about, in character coordinates (bind pose). */`,
    `export const PIVOTS: Record<PartName, [number, number]> = ${table('pivot')};`,
    `/** Where a held object goes, for hand parts. */`,
    `export const ANCHORS: Partial<Record<PartName, [number, number]>> = ${table('anchor')};`,
    '',
  ].join('\n\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const [name = 'sultan', flag] = process.argv.slice(2);
  const file = path.join(root, `src/characters/${name}/Art.tsx`);
  const code = await build(name);
  if (flag === '--check') {
    const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8') === code;
    console.log(same ? `${name}: Art.tsx matches its source` : `${name}: Art.tsx is stale, run node tools/svgr-build.mjs ${name}`);
    process.exit(same ? 0 : 1);
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, code);
  console.log(`${file}: ${(code.match(/^export const Part/gm) || []).length} parts`);
}
